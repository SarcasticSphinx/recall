import {
  ArrowLeft,
  ArrowRight,
  BookOpen,
  Brain,
  Check,
  Clock3,
  Code2,
  FlaskConical,
  Globe,
  GraduationCap,
  Heart,
  Languages,
  LayoutGrid,
  Lightbulb,
  LogIn,
  LogOut,
  Monitor,
  Moon,
  Music,
  Pencil,
  Plus,
  SlidersHorizontal,
  Sparkles,
  GalleryVerticalEnd,
  Sun,
  Target,
  Trash2,
  X,
  type LucideIcon,
  type LucideProps,
} from "lucide-react";
const icons: Record<string, LucideIcon> = {
  cards: GalleryVerticalEnd,
  sun: Sun,
  moon: Moon,
  monitor: Monitor,
  grid: LayoutGrid,
  settings: SlidersHorizontal,
  plus: Plus,
  arrow: ArrowRight,
  back: ArrowLeft,
  close: X,
  check: Check,
  spark: Sparkles,
  clock: Clock3,
  edit: Pencil,
  trash: Trash2,
  logout: LogOut,
  login: LogIn,
  book: BookOpen,
  brain: Brain,
  code: Code2,
  languages: Languages,
  science: FlaskConical,
  heart: Heart,
  globe: Globe,
  music: Music,
  graduation: GraduationCap,
  lightbulb: Lightbulb,
  target: Target,
};
export function Icon({
  name,
  size = 20,
  ...props
}: LucideProps & { name: string }) {
  const Component = icons[name] || GalleryVerticalEnd;
  return (
    <Component size={size} strokeWidth={1.6} aria-hidden="true" {...props} />
  );
}
